import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
test.setTimeout(60_000)
const path = '#/architectures/cursor-continuity/diagrams/'
async function openDocs(page: import('@playwright/test').Page) {
 const button = page.getByRole('button', { name: 'Open explanation' })
 if (await button.isVisible()) { await button.focus(); await page.keyboard.press('Enter') }
 const docs = page.locator('.c4-documentation:visible')
 await docs.getByRole('button', { name: 'Plain explanation', exact: true }).click()
 return docs
}
async function closeDocs(page: import('@playwright/test').Page) {
 if (await page.getByRole('button', { name: 'Close explanation' }).isVisible()) await page.keyboard.press('Escape')
}
test('guided source reading, keyboard drill, legend, draft STE and scenario alternatives', async ({ page }, info) => {
 await page.goto('./')
 await expect(page.locator('[data-layout-ready=true]')).toBeVisible()
 await expect(page.getByRole('heading', { name: 'Diagram key', exact: true })).toBeVisible()
 let docs = await openDocs(page)
 await expect(docs).toContainText('reading model, not a running simulation')
 await expect(docs.getByRole('link', { name: 'Git at any scale · Cursor', exact: true })).toHaveAttribute('href', 'https://cursor.com/blog/git-at-any-scale')
 await docs.getByRole('button', { name: 'STE100 text', exact: true }).click()
 await expect(docs).toContainText('ASD-STE100 Issue 9 · draft')
 await expect(docs).toContainText('Technical terms')
 await page.screenshot({ path: info.outputPath('context-explanation.png') })
 await closeDocs(page)
 const system = page.getByRole('link', { name: 'Open detail for Continuity', exact: true })
 await system.focus(); await page.keyboard.press('Enter')
 await expect(page).toHaveURL(/diagrams\/containers$/)
 await expect(page.locator('[data-layout-ready=true]')).toBeVisible()
 await page.getByRole('button', { name: 'Inspect Local Git repository', exact: true }).click()
 docs = await openDocs(page); await expect(docs).toContainText('warm cache'); await closeDocs(page)
 const server = page.getByRole('link', { name: 'Open detail for Continuity server', exact: true })
 await server.focus(); await page.keyboard.press('Enter')
 await expect(page).toHaveURL(/server-components$/)
 await expect(page.locator('[data-layout-ready=true]')).toBeVisible()
 const publication = page.locator('.c4-flow-canvas').getByRole('button', { name: 'Inspect Publication role', exact: true })
 await publication.focus(); await page.keyboard.press('Enter')
 docs = await openDocs(page); await expect(docs).toContainText('Upload alone does not make a push visible')
 await expect(docs).toContainText('inferred decomposition')
 await page.screenshot({ path: info.outputPath('inferred-responsibilities.png') })
 await closeDocs(page)
 await page.getByRole('link', { name: 'Up', exact: true }).click()
 await expect(page).toHaveURL(/containers\/elements\/server$/)
 await page.getByRole('link', { name: 'Push: durable publication', exact: true }).click()
 await page.getByLabel('Scenario step', { exact: true }).selectOption('durable-preparation')
 await expect(page.getByLabel('Unordered parallel branches')).toBeVisible()
 await expect(page.getByLabel('Scenario text alternative')).toContainText('no lockstep barrier')
 await page.getByLabel('Scenario step', { exact: true }).selectOption('publish-cas')
 await expect(page.locator('[data-overlay-id=publish-cas]')).toHaveCount(1)
 await page.locator('.c4-flow-canvas').scrollIntoViewIfNeeded()
 await page.screenshot({ path: info.outputPath('publication.png') })
 const share = page.url(); const fresh = await page.context().newPage(); await fresh.goto(share)
 await expect(fresh.getByLabel('Scenario step', { exact: true })).toHaveValue('publish-cas'); await fresh.close()
 await page.getByRole('link', { name: 'Read: freshness already matches', exact: true }).click()
 await expect(page.getByLabel('Scenario text alternative')).toContainText('304')
 await page.getByRole('link', { name: 'Read: catch up before serving', exact: true }).click()
 await expect(page.getByLabel('Scenario text alternative')).toContainText('200')
 await page.getByRole('link', { name: 'Gossip: optional catch-up notification', exact: true }).click()
 docs = await openDocs(page); await expect(docs).toContainText('Lost notifications'); await closeDocs(page)
 await page.getByRole('link', { name: 'Rebuild: missing local cache', exact: true }).click()
 docs = await openDocs(page); await expect(docs).toContainText('does not specify recovery time'); await closeDocs(page)
 await page.getByRole('link', { name: 'Compaction: reuse compacted packs', exact: true }).click()
 docs = await openDocs(page); await expect(docs).toContainText('Replicas reuse compacted packs'); await closeDocs(page)
 expect((await new AxeBuilder({ page }).analyze()).violations.filter(v => ['serious','critical'].includes(v.impact ?? ''))).toEqual([])
})
