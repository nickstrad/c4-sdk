import { expect, test } from '@playwright/test'
const deployment = '#/architectures/cursor-continuity/diagrams/deployment'
test('nested topology collapse, distinct replicas, keyboard inspection and logical drill/back', async ({ page }, info) => {
 await page.goto(`./${deployment}`)
 const topology=page.getByRole('region',{name:'Deployment topology'})
 await expect(page.locator('.c4-flow-canvas')).toBeVisible()
 await expect(page.locator('[data-node-id=server-a]')).toHaveCount(1)
 await expect(page.locator('[data-node-id=server-b]')).toHaveCount(1)
 await topology.getByRole('button',{name:'Collapse Illustrative host A',exact:true}).click()
 await expect(page.locator('[data-node-id=server-a]')).toHaveCount(0)
 await expect(page.locator('[data-node-id=server-b]')).toHaveCount(1)
 await expect(page.locator('[data-relationship-id=deployment-local-b]')).toHaveCount(0)
 await topology.getByRole('button',{name:'Inspect topology Continuity replica A',exact:true}).focus()
 await page.keyboard.press('Enter')
 await expect(page).toHaveURL(/elements\/server-a$/)
 await expect(page.locator('[data-node-id=server-a]')).toHaveCount(1)
 await topology.getByRole('button',{name:'Inspect topology Continuity replica B',exact:true}).click()
 await expect(page).toHaveURL(/elements\/server-b$/)
 await expect(topology.locator('[data-deployment-id=server-b]')).toHaveAttribute('data-selected','true')
 await expect(page.locator('[data-node-id=server-b] [data-element-id=server-b]')).toBeFocused()
 const viewport = await page.locator('.react-flow__viewport').getAttribute('style')
 await topology.getByRole('link',{name:'Open logical detail for Continuity replica B',exact:true}).click()
 await expect(page).toHaveURL(/diagrams\/server-components$/)
 await expect(page.getByRole('navigation').first()).not.toContainText('illustrative deployment')
 await page.getByRole('button',{name:'Back',exact:true}).click()
 await expect(page).toHaveURL(/diagrams\/deployment\/elements\/server-b$/)
 await expect(page.locator('[data-node-id=server-b]')).toHaveCount(1)
 await expect(page.locator('[data-node-id=server-b] [data-element-id=server-b]')).toBeFocused()
 await expect(page.locator('.react-flow__viewport')).toHaveAttribute('style',viewport!)
 const card = await page.locator('[data-node-id=server-b]').boundingBox(); const canvas = await page.locator('.c4-flow-canvas').boundingBox()
 expect(card!.x).toBeGreaterThanOrEqual(canvas!.x - 1); expect(card!.x + card!.width).toBeLessThanOrEqual(canvas!.x + canvas!.width + 1)
 expect(card!.y).toBeGreaterThanOrEqual(canvas!.y - 1); expect(card!.y + card!.height).toBeLessThanOrEqual(canvas!.y + canvas!.height + 1)
 await page.screenshot({path:info.outputPath('deployment-selected-replica.png'),fullPage:true})
 await topology.getByRole('button',{name:'Collapse Illustrative region',exact:true}).click()
 await expect(page).toHaveURL(/elements\/demo-region$/)
 await expect(page.locator('.c4-flow-node')).toHaveCount(1)
 await expect(topology).toContainText('6 elements hidden')
 await topology.getByText('All declared deployment relationships (3)',{exact:true}).click()
 await expect(topology).toContainText('Continuity replica B → Local cache instance')
 await topology.getByRole('button',{name:'Expand Illustrative region',exact:true}).click()
 await expect(page.locator('.c4-flow-node')).toHaveCount(5)
 await topology.getByRole('button',{name:'Expand Illustrative host A',exact:true}).click()
 await expect(page.locator('.c4-flow-node')).toHaveCount(7)
 await page.locator('.c4-flow-canvas').getByRole('button',{name:'Fit View',exact:true}).click()
 await page.screenshot({path:info.outputPath('deployment-expanded.png'),fullPage:true})
})
test('direct replica links resolve physical ancestors, expose source status, survive reload',async({page})=> {
 await page.goto(`./${deployment}/elements/server-a`)
 await expect(page.locator('[data-node-id=server-a]')).toHaveCount(1)
 await expect(page.getByRole('region',{name:'Deployment topology'})).toContainText('Instance of Continuity server')
 await expect(page.getByRole('region',{name:'Deployment topology'})).toContainText('planned')
 await page.reload();await expect(page.locator('[data-node-id=server-a]')).toHaveCount(1)
 await expect(page.locator('[data-node-id=server-a] [data-element-id=server-a]')).toBeFocused()
})
