import { expect, test } from '@playwright/test'
const push = '#/architectures/cursor-continuity/diagrams/push'
test('scenario reading controls, parallel overlays, history and Inspect preserve stable geometry', async ({ page }, info) => {
  let workerStarts = 0
  page.on('worker', () => { workerStarts++ })
  await page.goto(`./${push}?step=persist-wal`)
  await expect(page.locator('[data-layout-ready=true]')).toBeVisible()
  await expect(page.getByLabel('Scenario step', { exact: true })).toHaveValue('persist-wal')
  expect(await page.getByLabel('Scenario step', { exact: true }).evaluate(node => node.getBoundingClientRect().width)).toBeGreaterThan(180)
  await expect(page.locator('[data-overlay-id=persist-wal]')).toHaveCount(1)
  await expect.poll(() => page.workers().length).toBe(0)
  const settledWorkerStarts = workerStarts
  const geometry = () => page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(node => ({ id: node.getAttribute('data-id'), style: node.getAttribute('style') })))
  const before = await geometry()
  await page.getByRole('button', { name: 'Next selection', exact: true }).click()
  await expect(page).toHaveURL(/step=local-branch$/)
  await page.getByRole('button', { name: 'Previous selection', exact: true }).click()
  await expect(page).toHaveURL(/step=persist-wal$/)
  await page.getByLabel('Scenario step', { exact: true }).selectOption('ack-push')
  await expect(page.locator('[data-overlay-id=ack-push]')).toHaveAttribute('data-direction', 'reverse')
  await expect(page.locator('[data-overlay-id=ack-push] path')).toHaveAttribute('marker-start', /url/)
  await expect(page.locator('.c4-selected-interactions')).toContainText('Continuity server → Git developer')
  expect(await geometry()).toEqual(before)
  expect(workerStarts).toBe(settledWorkerStarts)
  await page.reload()
  await expect(page.getByLabel('Scenario step', { exact: true })).toHaveValue('ack-push')
  await page.getByRole('button', { name: 'Inspect Continuity server', exact: true }).click()
  await expect(page).toHaveURL(/diagrams\/push\/elements\/server\?step=ack-push$/)
  await page.goBack(); await expect(page).toHaveURL(/diagrams\/push\?step=ack-push$/)
  await page.goForward(); await expect(page).toHaveURL(/elements\/server\?step=ack-push$/)
  await page.getByLabel('Scenario step', { exact: true }).selectOption('push-story')
  await expect(page.locator('.c4-interaction-overlay')).toHaveCount(7)
  await expect(page.locator('[data-relationship-id=server-local] .c4-interaction-overlay')).toHaveCount(3)
  await expect(page.getByLabel('Scenario text alternative')).toContainText('no lockstep barrier')
  await expect(page.getByLabel('Scenario selections')).toContainText('not an execution timeline')
  await page.screenshot({ path: info.outputPath('dynamic-story.png'), fullPage: true })
  await page.getByLabel('Scenario step', { exact: true }).selectOption('durable-preparation')
  await expect(page.locator('.c4-interaction-overlay')).toHaveCount(3)
  await expect(page.getByLabel('Unordered parallel branches')).toBeVisible()
  await page.getByRole('link', { name: 'Up', exact: true }).click()
  await expect(page).not.toHaveURL(/step=/)
})
test('direct step reload and wrong-diagram or absent IDs are validated', async ({ page }) => {
  await page.goto(`./${push}?step=publish-cas`)
  await expect(page.getByLabel('Scenario step', { exact: true })).toHaveValue('publish-cas')
  await page.reload()
  await expect(page.locator('[data-overlay-id=publish-cas]')).toHaveCount(1)
  await page.goto(`./${push}?step=missing`)
  await expect(page.getByLabel('Resource diagnostics')).toContainText('Unknown scenario step')
  await page.goto('./#/architectures/cursor-continuity/diagrams/containers?step=persist-wal')
  await expect(page.getByLabel('Resource diagnostics')).toContainText('Unknown scenario step')
})
